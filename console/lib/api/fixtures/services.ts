export function getMockServiceDetail(id: string): ServiceDetail | undefined {
  const service = mockServices.find((s) => s.id === id)
  if (!service) return undefined

  const server =
    mockServers.find((s) => s.id === service.server_id) || mockServers[0]
  const project =
    mockProjects.find((p) => p.id === service.project_id) || mockProjects[0]
  const domains = mockDomains[service.id] || []

  const activeDeployment = service.active_deployment_id
    ? mockDeployments.find((d) => d.id === service.active_deployment_id) || null
    : null

  return {
    ...service,
    server,
    project,
    domains,
    active_deployment: activeDeployment,
    env_vars_count: 4,
  }
}
